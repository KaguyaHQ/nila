defmodule Nila.Banking.Parsers.HdfcV2 do
  @moduledoc """
  Parser for HDFC's newer digitally-signed statement layout.

  Poppler's raw reading order keeps each logical transaction together for this
  layout; the visual layout output interleaves wrapped narration between rows.
  """

  @behaviour Nila.Banking.Parser

  alias Nila.Banking.Parser

  @date ~r/^\d{2}\/\d{2}\/\d{4}$/
  @inline_row ~r/^(?<date>\d{2}\/\d{2}\/\d{4})\s+(?<narration>.+?)\s+(?<value_date>\d{2}\/\d{2}\/\d{4})\s+(?<withdrawal>[\d,]+\.\d{2})\s+(?<deposit>[\d,]+\.\d{2})\s+(?<balance>[\d,]+\.\d{2})$/
  @amount_row ~r/^(?:(?<reference>\S+)\s+)?(?<value_date>\d{2}\/\d{2}\/\d{4})\s+(?<withdrawal>[\d,]+\.\d{2})\s+(?<deposit>[\d,]+\.\d{2})\s+(?<balance>[\d,]+\.\d{2})$/

  @impl true
  def text_mode, do: :raw

  @impl true
  @spec parse(binary()) :: {:ok, map()} | {:error, term()}
  def parse(text) when is_binary(text) do
    with :ok <- hdfc_statement?(text),
         [_first | _rest] = transactions <- parse_transactions(text) do
      first = hd(transactions)
      last = List.last(transactions)
      {statement_from, statement_to} = statement_period(text, first["date"], last["date"])

      Parser.finalize(
        %{
          bank_code: "hdfc",
          account_number_masked: masked_account(text),
          statement_from: statement_from,
          statement_to: statement_to,
          meta: %{
            "bank" => "HDFC Bank",
            "parser" => "hdfc_text_v2",
            "balance_reconciled" => true
          }
        },
        transactions
      )
    else
      [] -> {:error, :unsupported_statement}
      error -> error
    end
  end

  defp parse_transactions(text) do
    {transactions, current} =
      text
      |> String.split("\n")
      |> Enum.reduce({[], nil}, &consume_line/2)

    transactions
    |> finish(current)
    |> Enum.reverse()
    |> Enum.map(&transaction/1)
    |> Enum.reject(&is_nil/1)
  end

  defp consume_line(line, {transactions, current}) do
    value = String.trim(line)

    case Regex.named_captures(@inline_row, value) do
      fields when is_map(fields) ->
        {[%{inline: fields} | finish(transactions, current)], nil}

      nil ->
        cond do
          Regex.match?(@date, value) ->
            {finish(transactions, current), %{date: value, lines: []}}

          is_map(current) ->
            {transactions, Map.update!(current, :lines, &(&1 ++ [value]))}

          true ->
            {transactions, current}
        end
    end
  end

  defp finish(transactions, nil), do: transactions
  defp finish(transactions, current), do: [current | transactions]

  defp transaction(%{date: date, lines: lines}) do
    case Enum.find_value(lines, fn line -> Regex.named_captures(@amount_row, line) end) do
      nil ->
        nil

      amounts ->
        narration =
          lines
          |> Enum.take_while(&(Regex.named_captures(@amount_row, &1) == nil))
          |> Enum.reject(&ignored_line?/1)
          |> Enum.join(" ")
          |> Parser.normalize_narration()

        %{
          "date" => Parser.numeric_date!(date, "/"),
          "value_date" => Parser.numeric_date!(amounts["value_date"], "/"),
          "narration" => narration,
          "reference" => amounts["reference"],
          "withdrawal_paise" => Parser.amount_paise!(amounts["withdrawal"]),
          "deposit_paise" => Parser.amount_paise!(amounts["deposit"]),
          "balance_paise" => Parser.amount_paise!(amounts["balance"])
        }
    end
  end

  defp transaction(%{inline: fields}) do
    %{
      "date" => Parser.numeric_date!(fields["date"], "/"),
      "value_date" => Parser.numeric_date!(fields["value_date"], "/"),
      "narration" => Parser.normalize_narration(fields["narration"]),
      "reference" => nil,
      "withdrawal_paise" => Parser.amount_paise!(fields["withdrawal"]),
      "deposit_paise" => Parser.amount_paise!(fields["deposit"]),
      "balance_paise" => Parser.amount_paise!(fields["balance"])
    }
  end

  defp ignored_line?(line) do
    line == "" or line == "HDFC BANK LIMITED" or String.starts_with?(line, "Page ") or
      String.starts_with?(line, "Generation Date") or
      String.starts_with?(line, "Generated by") or
      String.starts_with?(line, "Date Narration") or
      String.starts_with?(line, "*Closing Balance") or
      String.starts_with?(line, "Contents of this statement") or
      String.starts_with?(line, "State account branch GSTIN") or
      String.starts_with?(line, "HDFC Bank GSTIN")
  end

  defp hdfc_statement?(text) do
    if String.contains?(text, "HDFC BANK LIMITED") and
         String.contains?(text, "Withdrawal Amount Deposit Amount Closing Balance*") and
         String.contains?(text, "Statement From") do
      :ok
    else
      {:error, :unsupported_statement}
    end
  end

  defp masked_account(text) do
    case Regex.run(~r/Account number\s*: (\d+)/, text, capture: :all_but_first) do
      [number] -> Parser.mask_account(number)
      _missing -> nil
    end
  end

  defp statement_period(text, fallback_from, fallback_to) do
    case Regex.run(
           ~r/Statement From\s*: (\d{2}\/\d{2}\/\d{2})\s+TO\s*: (\d{2}\/\d{2}\/\d{2})/,
           text,
           capture: :all_but_first
         ) do
      [from, to] ->
        {Parser.numeric_date!(from, "/", :two_digit), Parser.numeric_date!(to, "/", :two_digit)}

      _missing ->
        {fallback_from, fallback_to}
    end
  end
end
